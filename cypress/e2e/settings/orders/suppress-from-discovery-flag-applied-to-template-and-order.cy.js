import uuid from 'uuid';
import { including } from '@interactors/html';
import CapabilitySets from '../../../support/dictionary/capabilitySets';
import {
  ACQUISITION_METHOD_NAMES_IN_PROFILE,
  APPLICATION_NAMES,
  CURRENCIES,
  ORDER_FORMAT_NAMES,
  ORDER_STATUSES,
  ORDER_TEMPLATE_FORM_ACCORDION_LABELS,
  ORDER_TYPES,
  POL_CREATE_INVENTORY_SETTINGS_VIEW,
  RECEIVING_WORKFLOW_NAMES,
} from '../../../support/constants';
import InstanceRecordView from '../../../support/fragments/inventory/instanceRecordView';
import InventoryInstance from '../../../support/fragments/inventory/inventoryInstance';
import InventoryInstances from '../../../support/fragments/inventory/inventoryInstances';
import OrderDetails from '../../../support/fragments/orders/orderDetails';
import OrderEditForm from '../../../support/fragments/orders/orderEditForm';
import OrderLineDetails from '../../../support/fragments/orders/orderLineDetails';
import OrderLineEditForm from '../../../support/fragments/orders/orderLineEditForm';
import OrderLines from '../../../support/fragments/orders/orderLines';
import Orders from '../../../support/fragments/orders/orders';
import NewOrganization from '../../../support/fragments/organizations/newOrganization';
import Organizations from '../../../support/fragments/organizations/organizations';
import OrderTemplateForm from '../../../support/fragments/settings/orders/orderTemplateForm';
import OrderTemplates from '../../../support/fragments/settings/orders/orderTemplates';
import SettingsMenu from '../../../support/fragments/settingsMenu';
import TopMenuNavigation from '../../../support/fragments/topMenuNavigation';
import Users from '../../../support/fragments/users/users';
import getRandomPostfix from '../../../support/utils/stringTools';

const SUPPRESS_LABEL = 'Suppress instance from discovery when generated by order';
const UNIT_PRICE = '10';
const QUANTITY = '1';

describe('Orders', () => {
  describe('Settings (Orders)', () => {
    let testData;

    before('Create test data', () => {
      const postfix = getRandomPostfix();

      testData = {
        organization: {
          ...NewOrganization.getDefaultOrganization(),
          name: `AT_C820864_Vendor_${postfix}`,
        },
        notSuppressedInstance: { title: `AT_C820864_FolioInstance_1_${postfix}` },
        suppressedInstance: { id: uuid(), title: `AT_C820864_FolioInstance_2_${postfix}` },
        templateName: `AT_C820864_OrderTemplate_${postfix}`,
        orderLineTitles: [1, 2].map(
          (lineNumber) => `AT_C820864_OrderLine_${lineNumber}_${postfix}`,
        ),
        poNumbers: [],
      };

      cy.getAdminToken();
      Organizations.createOrganizationViaApi(testData.organization);
      InventoryInstance.createInstanceViaApi({
        instanceTitle: testData.notSuppressedInstance.title,
      }).then(({ instanceData }) => {
        testData.notSuppressedInstance.id = instanceData.instanceId;
      });
      cy.getInstanceTypes({ limit: 1 }).then(([instanceType]) => {
        InventoryInstances.createFolioInstanceViaApi({
          instance: {
            id: testData.suppressedInstance.id,
            instanceTypeId: instanceType.id,
            title: testData.suppressedInstance.title,
            discoverySuppress: true,
          },
        });
      });

      cy.createTempUser([]).then((userProperties) => {
        testData.user = userProperties;

        cy.assignCapabilitiesToExistingUser(
          testData.user.userId,
          [],
          [
            CapabilitySets.uiOrdersSettingsView,
            CapabilitySets.uiOrdersSettingsOrderTemplatesCreate,
            CapabilitySets.uiOrdersSettingsOrderTemplatesEdit,
            CapabilitySets.uiOrdersOrdersCreate,
            CapabilitySets.uiOrdersOrdersEdit,
            CapabilitySets.uiInventoryInstanceView,
          ],
        );

        cy.login(testData.user.username, testData.user.password, {
          path: SettingsMenu.ordersOrderTemplatesPath,
          waiter: OrderTemplates.waitLoading,
        });
      });
    });

    after('Delete test data', () => {
      cy.getAdminToken();
      testData.poNumbers.forEach((poNumber) => Orders.deleteOrderByOrderNumberViaApi(poNumber));
      testData.orderLineTitles.forEach((title) => {
        InventoryInstances.deleteFullInstancesByTitleViaApi(title);
      });
      InventoryInstance.deleteInstanceViaApi(testData.notSuppressedInstance.id);
      InventoryInstance.deleteInstanceViaApi(testData.suppressedInstance.id);
      OrderTemplates.getOrderTemplateByNameViaApi(testData.templateName).then((template) => {
        if (template) {
          OrderTemplates.deleteOrderTemplateViaApi(template.id);
        }
      });
      Organizations.deleteOrganizationViaApi(testData.organization.id);
      Users.deleteViaApi(testData.user.userId);
    });

    it(
      'C820864 Suppress from discovery flag correctly applied to the order template and the order created from it (thunderjet)',
      { tags: ['extendedPath', 'thunderjet', 'C820864'] },
      () => {
        // Step 1: Click "New" button on the "Order templates" pane
        OrderTemplates.clickNewOrderTemplateButton();
        OrderTemplateForm.expandAccordion(ORDER_TEMPLATE_FORM_ACCORDION_LABELS.ITEM_DETAILS);
        OrderTemplateForm.checkItemDetailsFields([
          { label: 'suppressInstanceFromDiscovery', conditions: { checked: false } },
        ]);

        // Step 2: Click on the tool tip "i" icon next to the Suppress checkbox
        OrderTemplateForm.verifySuppressInstanceFromDiscoveryInfoPopover();

        // Step 3: Select Instance #1 (not suppressed) via "Title look-up"
        OrderTemplateForm.selectInstanceByTitleLookUp(testData.notSuppressedInstance.title);
        OrderTemplateForm.checkItemDetailsFields([
          { label: 'title', conditions: { value: testData.notSuppressedInstance.title } },
          {
            label: 'suppressInstanceFromDiscovery',
            conditions: { checked: false, disabled: true },
          },
        ]);

        // Step 4: Clear "Title" field and confirm "Remove instance connection" modal
        OrderTemplateForm.clearTitle();
        OrderLines.removeInstanceConnectionModal();
        OrderTemplateForm.checkItemDetailsFields([
          { label: 'title', conditions: { value: '' } },
          { label: 'suppressInstanceFromDiscovery', conditions: { disabled: false } },
        ]);

        // Step 5: Select Instance #2 (suppressed) via "Title look-up"
        OrderTemplateForm.selectInstanceByTitleLookUp(testData.suppressedInstance.title);
        OrderTemplateForm.checkItemDetailsFields([
          { label: 'title', conditions: { value: testData.suppressedInstance.title } },
          {
            label: 'suppressInstanceFromDiscovery',
            conditions: { checked: true, disabled: true },
          },
        ]);

        // Step 6: Clear "Title" field and confirm "Remove instance connection" modal
        OrderTemplateForm.clearTitle();
        OrderLines.removeInstanceConnectionModal();
        OrderTemplateForm.checkItemDetailsFields([
          { label: 'title', conditions: { value: '' } },
          {
            label: 'suppressInstanceFromDiscovery',
            conditions: { checked: true, disabled: false },
          },
        ]);

        // Step 7: Fill name, vendor, order type, acquisition method (Suppress - false), click "Save"
        OrderTemplateForm.fillOrderTemplateFields({
          templateInformation: { templateName: testData.templateName },
          poInformation: {
            organizationName: testData.organization.name,
            orderType: ORDER_TYPES.ONE_TIME,
          },
          poLineDetails: { acquisitionMethod: ACQUISITION_METHOD_NAMES_IN_PROFILE.PURCHASE },
        });
        // Checkbox stays checked after removing Instance #2 (suppressed): uncheck it
        OrderTemplateForm.clickSuppressInstanceFromDiscoveryCheckbox();
        OrderTemplateForm.checkItemDetailsFields([
          { label: 'suppressInstanceFromDiscovery', conditions: { checked: false } },
        ]);
        OrderTemplateForm.clickSaveButton();
        OrderTemplates.checkTemplateCreated(testData.templateName);

        // Step 8: Create an order from the template
        TopMenuNavigation.navigateToApp(APPLICATION_NAMES.ORDERS);
        Orders.selectOrdersPane();
        Orders.clickCreateNewOrder();
        OrderEditForm.selectOrderTemplate(testData.templateName);
        OrderEditForm.verifySelectedOrderTemplate(testData.templateName);
        // Wait until the template is applied (vendor comes from it)
        OrderEditForm.verifyOrderInformationSection([
          { label: 'vendor', conditions: { value: testData.organization.name } },
          { label: 'orderType', conditions: { value: ORDER_TYPES.ONE_TIME_API } },
        ]);
        OrderEditForm.clickSaveButton();
        OrderDetails.waitLoading();

        // Step 9: Click "Actions" in "PO lines" accordion and select "Add PO line"
        OrderDetails.selectAddPOLine();
        OrderLineEditForm.checkItemDetailsSection([
          { label: 'suppressInstanceFromDiscovery', conditions: { checked: false } },
        ]);
        OrderLineEditForm.checkOrderLineDetailsSection([
          {
            label: 'acquisitionMethod',
            conditions: { value: including(ACQUISITION_METHOD_NAMES_IN_PROFILE.PURCHASE) },
          },
        ]);

        // Step 10: Type title (no "Title look-up"), fill mandatory fields, click "Save & close"
        OrderLineEditForm.fillOrderLineFields({
          itemDetails: { title: testData.orderLineTitles[0] },
          poLineDetails: {
            orderFormat: ORDER_FORMAT_NAMES.PHYSICAL_RESOURCE,
            createInventory: POL_CREATE_INVENTORY_SETTINGS_VIEW.INSTANCE,
            receivingWorkflow: RECEIVING_WORKFLOW_NAMES.SYNCHRONIZED_ORDER_AND_RECEIPT_QUANTITY,
          },
          costDetails: { physicalUnitPrice: UNIT_PRICE, quantityPhysical: QUANTITY },
        });
        OrderLines.selectCurrency(CURRENCIES.USD);
        OrderLineEditForm.clickSaveButton({ orderLineCreated: true, orderLineUpdated: false });
        OrderLineDetails.waitLoading();
        OrderLineDetails.checkOrderLineDetails({
          itemDetails: [
            { key: SUPPRESS_LABEL, value: { checked: false, disabled: true }, checkbox: true },
          ],
        });
        OrderLines.getAssignedPOLNumber().then((polNumber) => {
          testData.poNumbers.push(polNumber.split('-')[0]);
        });

        // Step 11: Go back to the order and open it
        OrderLineDetails.backToOrderDetails();
        OrderDetails.openOrder();
        OrderDetails.checkOrderStatus(ORDER_STATUSES.OPEN);

        // Step 12: Open the PO line and click on the title link
        OrderDetails.selectPOLInOrder(0);
        OrderLineDetails.waitLoading();
        OrderLines.openInstanceInPOL(testData.orderLineTitles[0]);
        InstanceRecordView.waitLoading();
        InstanceRecordView.verifyMarkAsSuppressedFromDiscoveryWarning(false);

        // Step 13: Edit the template: check Suppress checkbox, click "Save"
        TopMenuNavigation.navigateToApp(APPLICATION_NAMES.SETTINGS);
        OrderTemplates.goToTemplatesFromOrders();
        OrderTemplates.selectTemplate(testData.templateName);
        OrderTemplates.openEditForm();
        OrderTemplateForm.expandAccordion(ORDER_TEMPLATE_FORM_ACCORDION_LABELS.ITEM_DETAILS);
        OrderTemplateForm.clickSuppressInstanceFromDiscoveryCheckbox();
        OrderTemplateForm.checkItemDetailsFields([
          { label: 'suppressInstanceFromDiscovery', conditions: { checked: true } },
        ]);
        OrderTemplateForm.clickSaveButton();
        OrderTemplates.checkTemplateCreated(testData.templateName);

        // Step 14: Create an order from the edited template
        TopMenuNavigation.navigateToApp(APPLICATION_NAMES.ORDERS);
        OrderLineDetails.backToOrderDetails();
        OrderDetails.closeOrderDetails();
        Orders.resetFilters();
        Orders.clickCreateNewOrder();
        OrderEditForm.selectOrderTemplate(testData.templateName);
        OrderEditForm.verifySelectedOrderTemplate(testData.templateName);
        OrderEditForm.verifyOrderInformationSection([
          { label: 'vendor', conditions: { value: testData.organization.name } },
          { label: 'orderType', conditions: { value: ORDER_TYPES.ONE_TIME_API } },
        ]);
        OrderEditForm.clickSaveButton();
        OrderDetails.waitLoading();

        // Step 15: Click "Actions" in "PO lines" accordion and select "Add PO line"
        OrderDetails.selectAddPOLine();
        OrderLineEditForm.checkItemDetailsSection([
          { label: 'suppressInstanceFromDiscovery', conditions: { checked: true } },
        ]);
        OrderLineEditForm.checkOrderLineDetailsSection([
          {
            label: 'acquisitionMethod',
            conditions: { value: including(ACQUISITION_METHOD_NAMES_IN_PROFILE.PURCHASE) },
          },
        ]);

        // Step 16: Type title (no "Title look-up"), fill mandatory fields, click "Save & close"
        OrderLineEditForm.fillOrderLineFields({
          itemDetails: { title: testData.orderLineTitles[1] },
          poLineDetails: {
            orderFormat: ORDER_FORMAT_NAMES.PHYSICAL_RESOURCE,
            createInventory: POL_CREATE_INVENTORY_SETTINGS_VIEW.INSTANCE,
            receivingWorkflow: RECEIVING_WORKFLOW_NAMES.SYNCHRONIZED_ORDER_AND_RECEIPT_QUANTITY,
          },
          costDetails: { physicalUnitPrice: UNIT_PRICE, quantityPhysical: QUANTITY },
        });
        OrderLines.selectCurrency(CURRENCIES.USD);
        OrderLineEditForm.clickSaveButton({ orderLineCreated: true, orderLineUpdated: false });
        OrderLineDetails.waitLoading();
        OrderLineDetails.checkOrderLineDetails({
          itemDetails: [
            { key: SUPPRESS_LABEL, value: { checked: true, disabled: true }, checkbox: true },
          ],
        });
        OrderLines.getAssignedPOLNumber().then((polNumber) => {
          testData.poNumbers.push(polNumber.split('-')[0]);
        });

        // Step 17: Go back to the order and open it
        OrderLineDetails.backToOrderDetails();
        OrderDetails.openOrder();
        OrderDetails.checkOrderStatus(ORDER_STATUSES.OPEN);

        // Step 18: Open the PO line and click on the title link
        OrderDetails.selectPOLInOrder(0);
        OrderLineDetails.waitLoading();
        OrderLines.openInstanceInPOL(testData.orderLineTitles[1]);
        InstanceRecordView.waitLoading();
        InstanceRecordView.verifyMarkAsSuppressedFromDiscoveryWarning(true);
      },
    );
  });
});
